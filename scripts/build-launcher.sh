#!/bin/zsh
# Builds "Job Board.app" — a chromeless launcher for the board — and installs it to /Applications.
# Re-run whenever board/artifact.url changes. Usage: scripts/build-launcher.sh [chrome-profile-dir]
#
# What it is: a tiny app bundle whose executable runs
#   open -na "Google Chrome" --args --profile-directory=<profile> --app=<board URL>
# Chrome's --app mode drops tabs, the address bar and the bookmarks bar. --profile-directory pins it
# to the profile signed in to claude.ai (the board is private; "Default" = the user's personal profile).
# -n matters: plain `open -a` ignores --args when Chrome is already running.
#
# Limitation (macOS): the window belongs to Chrome, so the Dock and Cmd+Tab show it under Chrome's
# icon. A separate Dock/Cmd+Tab identity needs Chrome's own "Install page as app" (a one-time manual
# step in Chrome's menu) — see the board's README note in the plan file.
set -euo pipefail
ROOT="${0:A:h:h}"
PROFILE="${1:-Default}"
URL="$(tr -d '[:space:]' < "$ROOT/board/artifact.url")"
CHROME_APP="/Applications/Google Chrome.app"
[[ -d "$CHROME_APP" ]] || { echo "Google Chrome not found at $CHROME_APP" >&2; exit 1; }
[[ "$URL" == https://claude.ai/* ]] || { echo "board/artifact.url doesn't look like a claude.ai URL: $URL" >&2; exit 1; }

BUILD="$ROOT/app"
APP="$BUILD/Job Board.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# ── Executable ────────────────────────────────────────────────────────────────
cat > "$APP/Contents/MacOS/JobBoard" <<EOF
#!/bin/zsh
# Generated by scripts/build-launcher.sh — edit that, not this.
exec /usr/bin/open -na "Google Chrome" --args --profile-directory="$PROFILE" --app="$URL"
EOF
chmod +x "$APP/Contents/MacOS/JobBoard"

# ── Info.plist ────────────────────────────────────────────────────────────────
# LSUIElement: the launcher itself exits in a fraction of a second; without this it would flash a
# bouncing icon. It can still be pinned to the Dock and found by Spotlight/Launchpad.
cat > "$APP/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Job Board</string>
  <key>CFBundleDisplayName</key><string>Job Board</string>
  <key>CFBundleIdentifier</key><string>local.jobhunt.jobboard</string>
  <key>CFBundleExecutable</key><string>JobBoard</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>LSUIElement</key><true/>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
</dict>
</plist>
EOF
plutil -lint "$APP/Contents/Info.plist" >/dev/null

# ── Icon: the board's 🗂️ favicon on a rounded tile in the board's ink color ─────
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
cat > "$TMP/icon.html" <<'EOF'
<!doctype html><html><head><meta charset="utf-8"><style>
html,body{margin:0;width:1024px;height:1024px;background:transparent}
.tile{position:absolute;left:100px;top:100px;width:824px;height:824px;border-radius:185px;
  background:linear-gradient(160deg,#243049,#121826);box-shadow:inset 0 0 0 6px rgba(217,162,72,.55);
  display:flex;align-items:center;justify-content:center;font-size:520px;line-height:1;
  font-family:"Apple Color Emoji"}
</style></head><body><div class="tile">🗂️</div></body></html>
EOF
perl -e 'alarm 45; exec @ARGV' "$CHROME_APP/Contents/MacOS/Google Chrome" --headless --disable-gpu \
  --no-sandbox --hide-scrollbars --user-data-dir="$TMP/profile" --default-background-color=00000000 \
  --window-size=1024,1024 --screenshot="$TMP/icon_1024.png" "file://$TMP/icon.html" >/dev/null 2>&1
[[ -s "$TMP/icon_1024.png" ]] || { echo "icon render failed" >&2; exit 1; }
SET="$TMP/AppIcon.iconset"; mkdir -p "$SET"
for s in 16 32 128 256 512; do
  sips -z $s $s "$TMP/icon_1024.png" --out "$SET/icon_${s}x${s}.png" >/dev/null
  d=$((s*2)); sips -z $d $d "$TMP/icon_1024.png" --out "$SET/icon_${s}x${s}@2x.png" >/dev/null
done
iconutil -c icns "$SET" -o "$APP/Contents/Resources/AppIcon.icns"

# ── Install ───────────────────────────────────────────────────────────────────
DEST="/Applications/Job Board.app"
rm -rf "$DEST"
cp -R "$APP" "$DEST"
touch "$DEST"                      # nudge Finder/Launchpad to pick up the new icon
/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister -f "$DEST" 2>/dev/null || true
echo "Installed: $DEST"
echo "  opens:   $URL"
echo "  profile: $PROFILE"
